CREATE TABLE `wish_payments` (
  `id` VARCHAR(30) NOT NULL,
  `user_id` VARCHAR(30) NOT NULL,
  `request_key` VARCHAR(36) NOT NULL,
  `intent_id` VARCHAR(80) NULL,
  `payment_id` VARCHAR(80) NULL,
  `event_id` VARCHAR(80) NULL,
  `amount` INTEGER NOT NULL DEFAULT 1000,
  `currency` VARCHAR(3) NOT NULL DEFAULT 'PHP',
  `wishes` INTEGER NOT NULL DEFAULT 100,
  `livemode` BOOLEAN NOT NULL,
  `status` VARCHAR(16) NOT NULL DEFAULT 'creating',
  `qr_image` LONGTEXT NULL,
  `expires_at` DATETIME(3) NOT NULL,
  `credited_at` DATETIME(3) NULL,
  `created_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updated_at` DATETIME(3) NOT NULL,
  UNIQUE INDEX `wish_payments_request_key_key` (`request_key`),
  UNIQUE INDEX `wish_payments_intent_id_key` (`intent_id`),
  UNIQUE INDEX `wish_payments_payment_id_key` (`payment_id`),
  UNIQUE INDEX `wish_payments_event_id_key` (`event_id`),
  INDEX `wish_payments_user_id_created_at_idx` (`user_id`, `created_at`),
  PRIMARY KEY (`id`),
  CONSTRAINT `wish_payments_user_id_fkey` FOREIGN KEY (`user_id`) REFERENCES `users` (`id`) ON DELETE RESTRICT ON UPDATE CASCADE
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
