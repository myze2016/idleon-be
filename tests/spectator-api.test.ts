import "./setup.js";
import assert from "node:assert/strict";
import { test } from "node:test";
import request from "supertest";
import { app } from "../src/app.js";
import { prisma } from "../src/lib/prisma.js";
import { env } from "../src/config/env.js";
import { hashPassword } from "../src/utils/password.js";
import { spawnEncounter, resolveEncounters, endExpedition } from "../src/repositories/expedition.repository.js";
import { summonDemonPrince, refreshSpectators } from "../src/repositories/spectator.repository.js";

test("Spectator chance persists across waves, click summons once, and Demon Prince rewards replay safely", async () => {
  const userId = "spectator-user";
  await prisma.user.create({ data: { id: userId, username: userId, name: "Spectator hunter", passwordHash: await hashPassword("Test123!") } });
  const fighter = await prisma.character.create({ data: { userId, name: "Hunter", weapon: "axe", upgradeLevel: 1000 } });
  const ids = [fighter.id];
  const agent = request.agent(app);
  await agent.post("/api/auth/login").set("Origin", env.corsOrigin).send({ username: userId, password: "Test123!" }).expect(200);
  const click = () => agent.post("/api/encounters/spectator").set("Origin", env.corsOrigin);
  await click().expect(409);
  const absent = await spawnEncounter(userId, ids, "tourney", true, true, () => 1);
  assert.equal(absent.yellowSpectator, false);
  const next = await spawnEncounter(userId, ids, "tourney", false, true, () => { throw Error("Waves must not reroll spectator"); });
  assert.equal(next.yellowSpectator, false);
  await click().expect(409);
  assert.equal((await spawnEncounter(userId, ids, "tourney", true, true, () => 0)).yellowSpectator, true);
  await click().expect(403);
  assert.equal(await prisma.encounter.count({ where: { userId, enemyType: "demon-prince" } }), 0);
  assert.equal((await prisma.user.findUniqueOrThrow({ where: { id: userId } })).tourneySpectator !== null, true);
  await prisma.questItem.create({ data: { userId, itemId: "zugwangs-evidence" } });
  await agent.post("/api/encounters/spectator").set("Origin", "https://other.example").expect(403);
  const concurrent = await Promise.all([click(), click()]);
  assert.deepEqual(concurrent.map((result) => result.status).sort(), [201, 409]);
  const prince = concurrent.find((result) => result.status === 201)!.body.data;
  assert.equal(prince.type, "demon-prince"); assert.equal(prince.boss, true); assert.equal(prince.stats.hp, 1000);
  assert.equal(await prisma.questItem.count({ where: { userId, itemId: "zugwangs-evidence" } }), 1);
  const user = await prisma.user.findUniqueOrThrow({ where: { id: userId } });
  const result = await resolveEncounters(userId, [prince.id]);
  assert.equal(result.won, true); assert.equal(result.expEarned, 1); assert.equal(result.goldEarned, 200);
  assert.equal(result.garnalandUnlocked, true); assert.equal(result.garnalandJustUnlocked, true);
  assert.equal(result.tourneyProgress.defeated, user.tourneyDefeats);
  assert.equal(result.tourneyProgress.target, user.tourneyBossAt);
  await resolveEncounters(userId, [prince.id]);
  assert.equal((await prisma.user.findUniqueOrThrow({ where: { id: userId } })).gold, 200);
  await click().expect(409);
  const noRoll = () => { throw Error("Defeated Demon Prince must permanently stop spectator rolls"); };
  assert.equal((await spawnEncounter(userId, ids, "tourney", true, true, noRoll)).yellowSpectator, false);
  assert.equal((await agent.get("/api/character").expect(200)).body.data.garnalandUnlocked, true);
  await click().expect(409);
  await spawnEncounter(userId, ids, "tourney", true, true, () => 0);
  await spawnEncounter(userId, ids, "meadow");
  await click().expect(409);
  await spawnEncounter(userId, ids, "tourney", true, true, () => 0);
  await endExpedition(userId);
  await assert.rejects(summonDemonPrince(userId));
  await agent.delete("/api/character").set("Origin", env.corsOrigin).expect(204);
  assert.equal((await agent.get("/api/character").expect(200)).body.data.garnalandUnlocked, true);
  await prisma.user.update({ where: { id: userId }, data: { tourneySpectator: { available: true, teamIds: ids } } });
  await click().expect(409);
});

test("Losing to Demon Prince leaves Garnaland locked and allows future spectator rolls", async () => {
  const userId = "prince-loss";
  await prisma.user.create({ data: { id: userId, username: userId, name: "Novice", passwordHash: "unused" } });
  const fighter = await prisma.character.create({ data: { userId, name: "Novice", weapon: "axe" } });
  const boss = await prisma.encounter.create({ data: { userId, enemyType: "demon-prince", location: "tourney", teamIds: [fighter.id] } });
  const result = await resolveEncounters(userId, [boss.id]);
  assert.equal(result.won, false); assert.equal(result.garnalandUnlocked, false);
  assert.equal((await prisma.user.findUniqueOrThrow({ where: { id: userId } })).garnalandUnlocked, false);
  assert.equal((await spawnEncounter(userId, [fighter.id], "tourney", true, true, () => 0)).yellowSpectator, true);
});

test("Each new spectator set rolls once, retries preserve the result, and progression stops yellow spectators", async () => {
  const userId = "crowd-user";
  await prisma.user.create({ data: { id: userId, username: userId, name: "Crowd watcher", passwordHash: "unused" } });
  const fighter = await prisma.character.create({ data: { userId, name: "Hunter", weapon: "axe", upgradeLevel: 1000 } });
  await spawnEncounter(userId, [fighter.id], "tourney", true, true, () => 1);
  const neverRoll = () => { throw Error("This call must not reroll spectators"); };
  assert.equal((await refreshSpectators(userId, 1, () => 0)).yellowSpectator, true);
  assert.equal((await refreshSpectators(userId, 1, neverRoll)).yellowSpectator, true);
  await assert.rejects(refreshSpectators(userId, 3, neverRoll));
  assert.equal((await refreshSpectators(userId, 2, () => 1)).yellowSpectator, false);
  assert.equal((await refreshSpectators(userId, 3, () => 0)).yellowSpectator, true);
  await prisma.questItem.create({ data: { userId, itemId: "zugwangs-evidence" } });
  const prince = await summonDemonPrince(userId);
  assert.equal((await refreshSpectators(userId, 4, neverRoll)).yellowSpectator, false);
  await resolveEncounters(userId, [prince.id]);
  assert.equal((await refreshSpectators(userId, 5, neverRoll)).yellowSpectator, false);
  await endExpedition(userId);
  assert.equal((await refreshSpectators(userId, 6, neverRoll)).yellowSpectator, false);
});
