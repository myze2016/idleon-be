import "./setup.js";
import assert from "node:assert/strict";
import { test } from "node:test";
import request from "supertest";
import { app } from "../src/app.js";
import { env } from "../src/config/env.js";
import { prisma } from "../src/lib/prisma.js";
import { hashPassword } from "../src/utils/password.js";
import { weaponTypes } from "../src/models/character.js";
import { baseStats } from "../src/models/character-stats.js";

test("starter grants 100 currency; wishes atomically spend currency and persist an owned character", async () => {
  await prisma.user.create({ data: { id: "wish-user", username: "wisher", name: "Wisher", passwordHash: await hashPassword("Test123!") } });
  const agent = request.agent(app);
  await request(app).post("/api/character/wish").set("Origin", env.corsOrigin).expect(401);
  await agent.post("/api/auth/login").set("Origin", env.corsOrigin).send({ username: "wisher", password: "Test123!" }).expect(200);
  await agent.post("/api/character/wish").set("Origin", env.corsOrigin).expect(409);
  const created = await agent.post("/api/character").set("Origin", env.corsOrigin).send({ name: "Starter", weapon: "bow" }).expect(201);
  assert.equal(created.body.data.wishCurrency, 100);
  assert.equal(created.body.data.characters.length, 1);
  assert.equal(created.body.data.characters[0].isStarter, true);
  await prisma.user.update({ where: { id: "wish-user" }, data: { experience: 17 } });
  assert.deepEqual(created.body.data.characters[0].stats, baseStats.bow);
  assert.equal(created.body.data.characters[0].timing.baseSpellCastTime, 1);
  assert.equal(created.body.data.characters[0].timing.attackInterval, 1 / 1.1);
  assert.equal(created.body.data.characters[0].timing.spellCastTime, 1 / 1.1);
  await agent.post("/api/character").set("Origin", env.corsOrigin).send({ name: "Extra", weapon: "staff" }).expect(409);
  await agent.post("/api/character/wish").set("Origin", "https://other.example").expect(403);
  await agent.post("/api/character/wish").expect(403);
  assert.equal((await prisma.user.findUniqueOrThrow({ where: { id: "wish-user" } })).wishCurrency, 100);
  await prisma.user.update({ where: { id: "wish-user" }, data: { wishCurrency: 99 } });
  await agent.post("/api/character/wish").set("Origin", env.corsOrigin).send({ wishCurrency: 100, cost: 1 }).expect(409);
  assert.equal((await prisma.user.findUniqueOrThrow({ where: { id: "wish-user" } })).wishCurrency, 99);
  assert.equal(await prisma.character.count({ where: { userId: "wish-user" } }), 1);
  await prisma.user.update({ where: { id: "wish-user" }, data: { wishCurrency: 100 } });
  const results = await Promise.all([1, 2].map(() => agent.post("/api/character/wish").set("Origin", env.corsOrigin).send({ weapon: "invalid", wishCurrency: 100, stats: { hp: 999999 } })));
  assert.deepEqual(results.map((result) => result.status).sort(), [201, 409]);
  const reward = results.find((result) => result.status === 201)!.body.data.reward;
  assert.ok(weaponTypes.includes(reward.weapon));
  assert.notEqual(reward.weapon, "bow");
  assert.deepEqual(reward.stats, baseStats[reward.weapon as typeof weaponTypes[number]]);
  assert.equal(reward.isStarter, false);
  assert.notEqual(reward.id, created.body.data.characters[0].id);
  const saved = await agent.get("/api/character").expect(200);
  assert.equal(saved.body.data.wishCurrency, 0);
  assert.deepEqual(saved.body.data.progression, { level: 2, totalExp: 17, exp: 7, expToNextLevel: 20 });
  assert.equal(saved.body.data.characters.length, 2);
  assert.deepEqual(saved.body.data.character, { name: "Starter", weapon: "bow" });
  assert.equal(saved.body.data.characters[0].isStarter, true);
  assert.deepEqual(saved.body.data.characters[0].stats, baseStats.bow);
  assert.ok(saved.body.data.characters.some((character: { id: string }) => character.id === reward.id));
  await agent.post("/api/character/wish").set("Origin", env.corsOrigin).expect(409);
  assert.equal(await prisma.character.count({ where: { userId: "wish-user" } }), 2);
  await agent.delete("/api/character").set("Origin", env.corsOrigin).expect(204);
  const reset = await agent.get("/api/character").expect(200);
  assert.equal(reset.body.data.wishCurrency, 0);
  assert.deepEqual(reset.body.data.characters, []);
  const restarted = await agent.post("/api/character").set("Origin", env.corsOrigin).send({ name: "New starter", weapon: "wand" }).expect(201);
  assert.equal(restarted.body.data.wishCurrency, 100);
  assert.equal(restarted.body.data.characters.length, 1);
});

test("concurrent wishes fill all missing types without duplicates and preserve currency after completion", async () => {
  await prisma.user.create({ data: { id: "collector", username: "collector", name: "Collector", passwordHash: await hashPassword("Test123!") } });
  const agent = request.agent(app);
  await agent.post("/api/auth/login").set("Origin", env.corsOrigin).send({ username: "collector", password: "Test123!" }).expect(200);
  await agent.post("/api/character").set("Origin", env.corsOrigin).send({ name: "First", weapon: "bow" }).expect(201);
  await prisma.user.update({ where: { id: "collector" }, data: { wishCurrency: 1200 } });
  const results = await Promise.all(Array.from({ length: 12 }, () => agent.post("/api/character/wish").set("Origin", env.corsOrigin).send({ weapon: "bow" })));
  assert.equal(results.filter((result) => result.status === 201).length, 10);
  assert.equal(results.filter((result) => result.status === 409).length, 2);
  const rewards = results.filter((result) => result.status === 201).map((result) => result.body.data.reward.weapon);
  assert.equal(new Set(rewards).size, 10);
  assert.equal(rewards.includes("bow"), false);
  const saved = await agent.get("/api/character").expect(200);
  assert.equal(saved.body.data.characters.length, 11);
  assert.deepEqual(new Set(saved.body.data.characters.map((character: { weapon: string }) => character.weapon)), new Set(weaponTypes));
  assert.equal(saved.body.data.wishCurrency, 200);
  const full = await agent.post("/api/character/wish").set("Origin", env.corsOrigin).expect(409);
  assert.equal(full.body.error.message, "You already own all 11 character types");
  assert.equal((await prisma.user.findUniqueOrThrow({ where: { id: "collector" } })).wishCurrency, 200);
});
